-- Pyramakerz ERP - Purchase Requisition persistence (v255)
-- Run ONCE in the self-hosted Supabase SQL editor before deploying the application.
-- This is additive and does not change or delete any existing orders or records.
BEGIN;
CREATE TABLE IF NOT EXISTS public.erp_purchase_requisitions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_key text NOT NULL UNIQUE,
  order_numbers bigint[] NOT NULL,
  form_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_by text NOT NULL DEFAULT '',
  updated_by text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT erp_pr_order_key_not_empty CHECK (length(order_key) BETWEEN 5 AND 500),
  CONSTRAINT erp_pr_form_is_object CHECK (jsonb_typeof(form_data) = 'object'),
  CONSTRAINT erp_pr_orders_present CHECK (cardinality(order_numbers) BETWEEN 1 AND 1000)
);
CREATE INDEX IF NOT EXISTS erp_pr_updated_at_idx ON public.erp_purchase_requisitions (updated_at DESC);
CREATE OR REPLACE FUNCTION public.erp_pr_touch_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  -- Preserve the identity of the person who created the document on updates.
  NEW.created_at := OLD.created_at;
  NEW.created_by := OLD.created_by;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS erp_pr_touch_updated_at_trigger ON public.erp_purchase_requisitions;
CREATE TRIGGER erp_pr_touch_updated_at_trigger
  BEFORE UPDATE ON public.erp_purchase_requisitions
  FOR EACH ROW EXECUTE FUNCTION public.erp_pr_touch_updated_at();
ALTER TABLE public.erp_purchase_requisitions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.erp_purchase_requisitions FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.erp_purchase_requisitions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.erp_purchase_requisitions_id_seq TO service_role;
-- No anon/authenticated policies: all access is through ERP server routes,
-- where feature permissions and component-level order scope are checked.
COMMIT;
